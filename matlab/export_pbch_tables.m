function export_pbch_tables()
%EXPORT_PBCH_TABLES  Tables and reference vectors for the Python SSB receiver (capture/nr_ssb.py).
%   matlab -batch "addpath('matlab'); export_pbch_tables"
%   Writes
%     capture/nr_pbch_tables.py          polar code of the PBCH (K 56, E 864, N 512):
%                                        INFO_POS(k) = u-domain position of bit k of the
%                                        CRC-attached payload (input interleaving included),
%                                        RM_MAP(e) = encoder output bit sent as rate-matched bit e
%     tests/fixtures/nr_pbch_vectors.json   nrBCH/nrPBCH/nrPBCHDMRS/nrPSS/nrSSS outputs and the
%                                        PBCH and DM-RS indices for a few cells, for tests
%   Both are derived from the 5G Toolbox's public functions (nrPolarEncode, nrRateMatchPolar),
%   so the Python code needs no 38.212 tables typed in by hand.
root = fileparts(fileparts(mfilename('fullpath')));
K = 56; E = 864; N = 512;
G = 1;
for i = 1:log2(N), G = kron([1 0; 1 1], G); end
infoPos = zeros(K, 1);
for k = 1:K
    in = zeros(K, 1); in(k) = 1;
    d = nrPolarEncode(in, E);                 % nMax 9, input interleaving on (downlink)
    u = mod(double(d(:)).'*G, 2);
    assert(sum(u) == 1, 'unit vector did not map to one u position');
    infoPos(k) = find(u) - 1;
end
rmMap = zeros(E, 1);
for b = 0:log2(N)-1
    e = nrRateMatchPolar(double(bitget((0:N-1).', b + 1)), K, E);
    rmMap = rmMap + double(e)*2^b;
end
% check: encoding a random payload by hand with these tables equals nrPolarEncode + nrRateMatchPolar
rng(7);
c = randi([0 1], K, 1);
u = zeros(1, N); u(infoPos + 1) = c;
d = mod(u*G, 2).';
assert(isequal(d(rmMap + 1), double(nrRateMatchPolar(nrPolarEncode(c, E), K, E))), 'table check failed');

f = fopen(fullfile(root, 'capture', 'nr_pbch_tables.py'), 'w');
fprintf(f, '"""Polar code of the NR PBCH (TS 38.212 7.1.4-7.1.5: K = 56, E = 864, N = 512).\n\n');
fprintf(f, 'Generated by matlab/export_pbch_tables.m from nrPolarEncode / nrRateMatchPolar (5G Toolbox,\n');
fprintf(f, 'MATLAB %s) on %s. Do not edit.\n\n', version('-release'), char(datetime('now', 'Format', 'yyyy-MM-dd')));
fprintf(f, 'INFO_POS[k]: u-domain position of bit k of the CRC-attached BCH payload (input interleaving\n');
fprintf(f, 'included); all other u positions are frozen to 0.\nRM_MAP[e]: index of the encoder output bit sent as rate-matched bit e.\n"""\n\n');
fprintf(f, 'K, E, N = %d, %d, %d\n\n', K, E, N);
fprintf(f, 'INFO_POS = (%s)\n\n', strjoin(compose('%d', infoPos), ', '));
fprintf(f, 'RM_MAP = (\n');
for r = 1:24:E
    fprintf(f, '    %s,\n', strjoin(compose('%d', rmMap(r:min(E, r+23))), ', '));
end
fprintf(f, ')\n');
fclose(f);

% reference vectors
cases = struct('pci', {0, 20, 165, 166, 503, 1007}, 'sfn', {0, 655, 870, 871, 1023, 513}, ...
    'hrf', {0, 1, 0, 1, 0, 1}, 'issb', {0, 1, 0, 3, 2, 3}, 'kssb', {0, 17, 6, 6, 23, 3});
V = struct('pci', {}, 'sfn', {}, 'hrf', {}, 'issb', {}, 'kssb', {}, 'trblk', {}, 'cw', {}, ...
    'pbch', {}, 'dmrs', {}, 'pss', {}, 'sss', {}, 'pbchInd', {}, 'dmrsInd', {}, 'dec', {});
for i = 1:numel(cases)
    cs = cases(i);
    trblk = randi([0 1], 24, 1);
    trblk(1) = 0;                                   % BCCH-BCH-Message choice: mib
    cw = nrBCH(trblk, cs.sfn, cs.hrf, 4, cs.kssb, cs.pci);
    sym = nrPBCH(cw, cs.pci, cs.issb);
    dm = nrPBCHDMRS(cs.pci, cs.issb + 4*cs.hrf);
    [~, err, tb, lsb, hrf, msb] = nrBCHDecode(1 - 2*double(cw), 8, 4, cs.pci);
    v = cs;
    v.trblk = trblk.';
    v.cw = double(cw).';
    v.pbch = [real(sym) imag(sym)].';
    v.dmrs = [real(dm) imag(dm)].';
    v.pss = nrPSS(cs.pci).';
    v.sss = nrSSS(cs.pci).';
    v.pbchInd = double(nrPBCHIndices(cs.pci)).' - 1;     % 0-based, column-major 240 x 4
    v.dmrsInd = double(nrPBCHDMRSIndices(cs.pci)).' - 1;
    v.dec = struct('err', double(err), 'trblk', double(tb).', 'lsbsfn', double(lsb).', ...
        'hrf', double(hrf), 'msbidxoffset', double(msb));
    V(end+1) = v; %#ok<AGROW>
end
f = fopen(fullfile(root, 'tests', 'fixtures', 'nr_pbch_vectors.json'), 'w');
fprintf(f, '%s', jsonencode(V));
fclose(f);
fprintf('export_pbch_tables: %d info positions, %d rate-matching entries, %d vectors\n', K, E, numel(V));
end
